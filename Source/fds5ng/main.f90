WRITE(LU_ERR,'(A,I0,A,F9.2,A)') ' R29h: продолжение цепочки, звено ',N_CHAIN, &
      ' (t>=',T_CHAIN,' с): RESTART=.TRUE.'
END SUBROUTINE CHAIN_CHECK

LOGICAL FUNCTION CHAIN_ARMED()
! Гарды (прогресс времени, глубина цепочки) и запись нового маркера
INTEGER :: IU,IOS,N_CHAIN
REAL(EB) :: T_PREV,T_KILL
LOGICAL :: EX
CHARACTER(32) :: ENV_STR
CHARACTER(80) :: FN_CHAIN
! R29l: FDS5NG_NO_CHAIN — выключатель авто-цепочки (оболочка Fenix+ ведёт
! собственную процедуру detectors->finish и ждёт выхода процесса на KILL)
CALL GET_ENVIRONMENT_VARIABLE('FDS5NG_NO_CHAIN',ENV_STR)
IF (LEN_TRIM(ENV_STR)>0) THEN
   WRITE(FN_CHAIN,'(A,A)') TRIM(CHID),'.chain'
   INQUIRE(FILE=FN_CHAIN,EXIST=EX)
   IF (EX) THEN
      IU = 981
      OPEN(IU,FILE=FN_CHAIN,STATUS='OLD',IOSTAT=IOS)
      IF (IOS==0) CLOSE(IU,STATUS='DELETE')
   ENDIF
   CHAIN_ARMED = .FALSE.
   RETURN
ENDIF
! R29m: под MPI-запускателем (mpiexec/hydra, есть PMI_FD) авто-цепочка
! выключена: потомок унаследовал бы PMI-канал и падал бы в MPI_Init,
! а оркестровку рестарта ведёт оболочка
CALL GET_ENVIRONMENT_VARIABLE('PMI_FD',ENV_STR)
IF (LEN_TRIM(ENV_STR)==0) CALL GET_ENVIRONMENT_VARIABLE('PMI_RANK',ENV_STR)
IF (LEN_TRIM(ENV_STR)>0) THEN
   WRITE(LU_ERR,'(A)') ' R29m: запуск под MPI-запускателем — авто-цепочка отключена'
   WRITE(FN_CHAIN,'(A,A)') TRIM(CHID),'.chain'
   INQUIRE(FILE=FN_CHAIN,EXIST=EX)
   IF (EX) THEN
      IU = 981
      OPEN(IU,FILE=FN_CHAIN,STATUS='OLD',IOSTAT=IOS)
      IF (IOS==0) CLOSE(IU,STATUS='DELETE')
   ENDIF
   CHAIN_ARMED = .FALSE.
   RETURN
ENDIF
T_KILL = MINVAL(T(1:NMESHES))
WRITE(FN_CHAIN,'(A,A)') TRIM(CHID),'.chain'
T_PREV = -1.E10_EB
N_CHAIN = 0
INQUIRE(FILE=FN_CHAIN,EXIST=EX)
IF (EX) THEN
   IU = 981
   OPEN(IU,FILE=FN_CHAIN,STATUS='OLD',IOSTAT=IOS)
   IF (IOS==0) THEN
      READ(IU,*,IOSTAT=IOS) T_PREV,N_CHAIN
      IF (IOS/=0) THEN
         T_PREV = -1.E10_EB
         N_CHAIN = 0
      ENDIF
      CLOSE(IU)
   ENDIF
ENDIF
IF (T_KILL<=T_PREV+1.E-6_EB .OR. N_CHAIN>=32) THEN
   IF (EX) THEN
      OPEN(IU,FILE=FN_CHAIN,STATUS='OLD',IOSTAT=IOS)
      IF (IOS==0) CLOSE(IU,STATUS='DELETE')
   ENDIF
   CHAIN_ARMED = .FALSE.
   RETURN
ENDIF
IU = 981
OPEN(IU,FILE=FN_CHAIN,STATUS='REPLACE',IOSTAT=IOS)
IF (IOS/=0) THEN
   CHAIN_ARMED = .FALSE.
   RETURN
ENDIF
WRITE(IU,*) T_KILL,N_CHAIN+1
CLOSE(IU)
CHAIN_ARMED = .TRUE.
END FUNCTION CHAIN_ARMED

